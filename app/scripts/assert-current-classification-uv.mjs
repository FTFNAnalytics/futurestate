import assert from 'node:assert/strict';
import {readFile,readdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
import {claimReviews57UV} from './content-205-216/claim-reviews-57uv.mjs';
import {verifyClassifiedInput} from './lib/classification-review.mjs';
import {createSignalProjection} from '../src/lib/signal-classification.mjs';
import {readShelfInputs} from './lib/read-shelf-inputs.mjs';
import {createShelfData} from '../src/lib/shelf-data.mjs';
import {searchShelf} from '../src/lib/shelf-search.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
const read=async path=>JSON.parse(await readFile(join(root,path),'utf8'));
const ledger=await read('src/data/phase-206-editorial-classification.json');
const pins=await read('scripts/content-205-216/claim-review-inputs.json');
const operations=await read('src/data/phase-207-current-operations.json');
const input=await readShelfInputs(root),snapshot=JSON.stringify(input);
const projection=createSignalProjection(ledger.records),shelves=createShelfData(input,ledger,operations).shelves;
assert.equal(JSON.stringify(input),snapshot);
const ids=claimReviews57UV.map(r=>r.id);
const files=(await readdir(join(root,'src/content/signals'))).filter(f=>/^signal-57[uv]-.*\.mdx$/.test(f));
assert.deepEqual([...ids].sort(),files.map(f=>f.slice(0,-4)).sort(),'No U/V record may be silently omitted or automatically classified');
assert.equal(ids.length,126);assert.equal(new Set(ids).size,126);
assert.equal(new Set(claimReviews57UV.map(r=>r.reason)).size,126,'Every record needs its individual rationale');
assert.equal(claimReviews57UV.filter(r=>r.type==='FTFN method/test note').length,108);
assert.equal(claimReviews57UV.filter(r=>r.type==='Research docket').length,18);
for(const phase of ['u','v']){
  const batch=claimReviews57UV.filter(r=>r.id.startsWith(`signal-57${phase}-`));
  assert.equal(batch.length,63);assert.equal(batch.filter(r=>r.type==='Research docket').length,9);
}
const contracts=new Map();
for(const review of claimReviews57UV){
  const record=ledger.records.find(r=>r.id===review.id);assert(record);
  const raw=await readFile(join(root,'src/content/signals',record.source_file),'utf8');
  const body=raw.match(/^---\r?\n[\s\S]*?\r?\n---\r?\n([\s\S]*)$/)?.[1];assert(body);
  verifyClassifiedInput({id:review.id,body:raw,excerpt:review.excerpt,expectedHash:pins.records[review.id]});
  assert(body.includes(review.excerpt),'The matched excerpt must occur in the actual body');
  assert.equal(record.claim_review_complete,true);assert.equal(record.content_type,review.type);
  assert.equal(record.reason,review.reason);assert.equal(record.review_excerpt,review.excerpt);
  assert.equal(record.classification_review_date,'2026-09-14');assert.equal(record.reviewed_source_sha256,pins.records[review.id]);
  assert.equal(record.correction.title,review.title);assert.equal(record.correction.summary,review.summary);
  assert(record.correction.title.startsWith('FTFN '));assert.match(review.summary,/historical FTFN/);
  assert.equal(record.correction.evidence_quality,'Internal FTFN record — not external outcome evidence');
  assert.equal(record.correction.verification_status,'Editorial classification reviewed; external outcome not verified');
  assert.equal(record.correction.maturity_level,'Not an external maturity assessment');
  assert.equal(record.correction.claim_scope,'Internal FTFN record');
  assert.equal(record.correction.local_evidence_level,'Not local operating evidence');
  assert.equal(record.current_feed_eligible,false);
  assert.equal(record.prior.evidence_quality,'Official Data');assert.equal(record.prior.verification_status,'Verified Against Primary Source');
  const original={data:{...input.signals.find(r=>r.id===review.id),...record.prior,id:review.id,slug:record.slug}};
  const priorSnapshot=JSON.stringify(original),current=projection.project(original);
  assert.equal(JSON.stringify(original),priorSnapshot);
  for(const [key,value]of Object.entries(record.correction))assert.equal(current.data[key],value,`Unpropagated field: ${review.id}/${key}`);
  for(const key of ['id','slug','source_ids','record_status','captured_date'])assert.deepEqual(current.data[key],original.data[key],`Historical field changed: ${review.id}/${key}`);
  assert.equal(projection.eligible(current),false);
  const archive=shelves.classification.find(r=>r.id===review.id);assert(archive);
  assert.equal(archive.title,review.title);assert.equal(archive.summary,review.reason);
  assert.deepEqual(archive.filters.type,[review.type]);assert.equal(archive.route,`/signals/${record.slug}/`);
  assert(searchShelf(shelves.classification,{q:review.title,type:review.type}).some(r=>r.id===review.id));
  for(const [kind,rows]of Object.entries(shelves))if(kind==='signals'||kind.startsWith('topic-')||kind.startsWith('local-'))assert(!rows.some(r=>r.id===review.id),`Feed hold lost: ${kind}/${review.id}`);
  assert.throws(()=>verifyClassifiedInput({id:review.id,body:`${raw}\nNew claim without a new review.`,excerpt:review.excerpt,expectedHash:pins.records[review.id]}),/individual re-review required/);
  if(review.type==='Research docket'){
    assert.equal(record.prior.record_status,'In Review');assert(body.includes('Trigger state: **not fired**'));
    assert(review.excerpt.startsWith('Reopening contract: REOPEN-'));
    contracts.set(review.excerpt,(contracts.get(review.excerpt)??0)+1);
    const next=body.match(/^Next action: (.+)$/m)?.[1];assert(next&&next.length>20);
  }else assert.equal(record.prior.record_status,'Published');
}
assert.equal(contracts.size,9);assert([...contracts.values()].every(count=>count===2),'Each named hold needs separate U and V history');
const pending=ledger.records.filter(r=>!r.claim_review_complete);
assert.equal(pending.length,ledger.remaining_individual_reviews);
assert(pending.every(r=>r.content_type==='Unclassified — review pending'&&!r.correction));
const update=await read('src/content/updates/2026-09-14-57uv-individual-classifications.json');
assert.deepEqual([...update.affected_record_ids].sort(),[...ids].sort());
for(const id of ids)assert(update.related_paths.includes(`/signals/${ledger.records.find(r=>r.id===id).slug}/`));
assert.match(update.evidence_note,/not newly run/);assert.match(update.publication_effect,/held/);
assert(searchShelf(shelves.updates,{q:update.receipt_id}).some(r=>r.id===update.id));
console.log(`U/V classification passed: 126 individual reviews, 108 method notes, 18 dockets across 9 distinct contracts, exact full-input pins, current field/search/archive propagation and preserved feed/publication holds. ${pending.length} individual reviews remain.`);
