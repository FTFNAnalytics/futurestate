import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
import {goldenMarsSignalReview as review, goldenMarsSignalContext, projectGoldenMarsSignalData} from '../src/lib/golden-mars-signal-review.mjs';
import {createSignalProjection, projectSignal, isCurrentFeedEligible, signalClassification} from '../src/lib/signal-classification.mjs';
import {readShelfInputs} from './lib/read-shelf-inputs.mjs';
import {createShelfData} from '../src/lib/shelf-data.mjs';
import {searchShelf} from '../src/lib/shelf-search.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
const read=p=>readFile(join(root,p),'utf8');
const hash=value=>createHash('sha256').update(value).digest('hex');
const raw=await read(review.source_file),input=await readShelfInputs(root);
assert.equal(hash(raw),review.source_sha256,'Historical Golden-Mars source changed');
const data=input.signals.find(s=>s.id===review.signal_id);
assert(data);assert.equal(data.title,review.prior.title);assert.equal(data.summary,review.prior.summary);
assert.equal(data.slug,review.slug);assert.deepEqual(data.source_ids,review.source_ids);
for(const field of ['dependencies','local_implications'])for(const value of review.prior[field])assert(raw.includes(JSON.stringify(value)));
const full={...data,dependencies:review.prior.dependencies,local_implications:review.prior.local_implications,published_date:'2026-04-09'};
const before=JSON.stringify(full),current=projectGoldenMarsSignalData(full);
assert.equal(JSON.stringify(full),before,'Projection mutated historical input');
for(const [key,value] of Object.entries(review.current))assert.deepEqual(current[key],value,key);
for(const key of Object.keys(full).filter(k=>!Object.hasOwn(review.current,k)))assert.deepEqual(current[key],full[key],`Changed non-review field ${key}`);
assert.deepEqual(projectGoldenMarsSignalData(full,'2026-09-21'),full);
assert.deepEqual(projectGoldenMarsSignalData(current),current,'Projection is not idempotent');
const dated={...full,last_reviewed_date:new Date('2026-07-24T00:00:00Z')};
assert.equal(projectGoldenMarsSignalData(dated).last_reviewed_date.toISOString(),'2026-09-22T00:00:00.000Z');
assert.equal(dated.last_reviewed_date.toISOString(),'2026-07-24T00:00:00.000Z');
assert.throws(()=>projectGoldenMarsSignalData(full,'2026-02-30'),/ISO calendar date/);
assert.throws(()=>projectGoldenMarsSignalData(full,'2026-99-30'),/ISO calendar date/);
assert.throws(()=>projectGoldenMarsSignalData({...full,slug:'wrong-case'}),/identity drift/);
assert.throws(()=>projectGoldenMarsSignalData({...full,source_ids:[review.source_ids[1]]}),/identity drift/);
assert.throws(()=>projectGoldenMarsSignalData({...full,title:'New unreviewed headline'}),/metadata drift/);
assert.throws(()=>projectGoldenMarsSignalData({...full,title:review.current.title}),/metadata drift/);
assert.throws(()=>projectGoldenMarsSignalData({...full,dependencies:['unreviewed dependency']}),/metadata drift/);
assert.equal(goldenMarsSignalContext('unrelated'),null);
assert.equal(signalClassification(review.signal_id),null);
assert.equal(isCurrentFeedEligible(projectSignal({data:full})),true);
assert.equal(createSignalProjection([{id:review.signal_id,current_feed_eligible:false}]).eligible({data:full}),false,'Dated correction must not override a feed hold');
for(const other of input.signals.filter(s=>s.id!==review.signal_id))assert.equal(projectGoldenMarsSignalData(other),other,'Other signal metadata changed');
const context=goldenMarsSignalContext(review.signal_id);
assert.equal(review.review_date,'2026-09-22');assert.equal(review.independent_review,false);assert.equal(review.approval_receipt_id,null);
assert.equal(hash(JSON.stringify(context.source_checks)),'7cb5752ac71d304e7ee7fcc5069a1bd02bcc07a26fa42a54da018766436adee6','Exact retained findings changed; re-review propagation');
assert.equal(context.source_checks.length,3);
assert(context.source_checks.every(s=>s.source_id===review.source_ids[0]&&s.profile_url&&s.relation&&s.captured_sha256));
const update=JSON.parse(await read(`src/content/updates/2026-09-22-golden-mars-signal-followthrough.json`));
assert.equal(update.id,review.update_id);assert.equal(update.receipt_id,review.review_id);assert.deepEqual(update.affected_record_ids,[review.signal_id]);
const ledger=JSON.parse(await read('src/data/phase-206-editorial-classification.json'));
const operations=JSON.parse(await read('src/data/phase-207-current-operations.json'));
const snapshot=JSON.stringify(input),shelves=createShelfData(input,ledger,operations).shelves;
assert.equal(JSON.stringify(input),snapshot);
let cards=0;
for(const records of Object.values(shelves))for(const card of records.filter(r=>r.id===review.signal_id)){
  cards++;assert.equal(card.title,review.current.title);assert.equal(card.summary,review.current.summary);
}
assert(cards>3,'Expected signal across topic, source and relationship shelves');
assert(searchShelf(shelves.signals,{q:'Golden-Mars Route 3A'}).some(r=>r.id===review.signal_id));
assert(!searchShelf(shelves.signals,{q:'preferred route remains subject'}).some(r=>r.id===review.signal_id));
console.log(`Golden-Mars dated signal assertions passed: preserved source, exact retained artifacts, date/idempotence/drift boundaries, unchanged eligibility and ${cards} current shelf cards.`);
