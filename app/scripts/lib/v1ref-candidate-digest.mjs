export async function computeV1refCandidateDigest({ appRoot = defaultAppRoot, aggregate } = {}) {
  const dataRoot = join(appRoot, "src", "data");
  const updatesRoot = join(appRoot, "src", "content", "updates");
  const docsRoot = resolve(appRoot, "..", "docs", "work-packages");
  const artifacts = [];

  for (const definition of v1refPhaseDefinitions) {
    artifacts.push({
      path: `src/data/${definition.file}`,
      content: await readFile(join(dataRoot, definition.file)),
    });
    const updateName = `${v1refEffectiveDate}-phase-${definition.phase}.json`;
    artifacts.push({
      path: `src/content/updates/${updateName}`,
      content: await readFile(join(updatesRoot, updateName)),
    });
    artifacts.push({
      path: `docs/work-packages/${definition.workPackage}`,
      content: await readFile(join(docsRoot, definition.workPackage)),
    });
  }

  for (const relativePath of new Set(integrationFiles)) {
    artifacts.push({ path: relativePath, content: await readFile(join(appRoot, relativePath)) });
  }

  const candidate = aggregate ?? JSON.parse(await readFile(join(dataRoot, "v1-public-reference-edition.json"), "utf8"));
  artifacts.push({ path: "src/data/v1-public-reference-edition.json#normalized", content: Buffer.from(canonicalV1refJson(normalizeV1refAggregate(candidate))) });

  const hash = createHash("sha256");
  for (const artifact of artifacts.sort((a, b) => a.path.localeCompare(b.path))) {
    hash.update(`${artifact.path}\0`);
    hash.update(artifact.content);
    hash.update("\0");
  }

  return {
    algorithm: "sha256",
    digest: hash.digest("hex"),
    artifact_count: artifacts.length,
    artifact_manifest_digest: sha256V1ref(canonicalV1refJson(artifacts.map(({ path, content }) => ({ path, sha256: sha256V1ref(content) })))),
    artifact_paths: artifacts.map(({ path }) => path),
  };
}

export function isValidV1refValidationReceipt({ receipt, aggregate, candidateDigest }) {
  const digest = typeof candidateDigest === "string" ? candidateDigest : candidateDigest?.digest;
  const manifestDigest = typeof candidateDigest === "object" ? candidateDigest?.artifact_manifest_digest : receipt?.artifact_manifest_digest;
  return Boolean(
    receipt
    && receipt.receipt_id
    && receipt.receipt_type === "Full local reference validation"
    && receipt.phase === 204
    && receipt.validated_phase_range === "181–204"
    && receipt.status === "Passed"
    && receipt.validator_contract_version === v1refValidatorContractVersion
    && receipt.scope === v1refValidationScope
    && receipt.artifact_digest === digest
    && receipt.artifact_manifest_digest === manifestDigest
    && receipt.effective_date === aggregate?.effective_date
    && receipt.phase_count === 24
    && receipt.primary_records === aggregate?.counts?.primary_records
    && receipt.public_html_routes === aggregate?.counts?.public_html_routes
    && receipt.public_json_exports === aggregate?.counts?.public_json_exports
    && receipt.publication_updates === aggregate?.counts?.publication_updates
    && receipt.owner_acceptance === false
    && receipt.github_publication_authorized === false
    && receipt.hosted_deployment_authorized === false
    && receipt.public_launch_authorized === false
    && receipt.v1_promotion_state === "Held"
  );
}
