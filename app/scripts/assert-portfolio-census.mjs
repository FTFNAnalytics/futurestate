import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {makeIdentityIndex, attachIdentity} from './build-portfolio-census.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const get = async path => JSON.parse(await readFile(resolve(root,path), 'utf8'));
const registry = await get('app/src/data/phase-116-coverage-architecture.json');
const atlas = await get('app/src/data/phase-119-deep-project-place-atlas.json');
const {index, records} = makeIdentityIndex(registry, atlas);
assert.equal(records.length, 39);
assert.equal(index.get('Project:119-PROJECT-001'), index.get('Project:casebook-tsmc-arizona'));
assert.throws(() => attachIdentity(index, 'Place', '119-PROJECT-001', {}), /Unresolved/);
assert.throws(() => attachIdentity(index, 'Project', 'TSMC Arizona', {}), /Unresolved/);
const duplicate = structuredClone(atlas);
duplicate.projects[1].legacy_ids.push('119-PROJECT-001');
assert.throws(() => makeIdentityIndex(registry, duplicate), /Conflicting/);
const report = await get('docs/release-reviews/2026-09-22/portfolio-census.json');
assert.equal(report.summary.canonical_projects, 24);
assert.equal(report.summary.canonical_places, 15);
assert.equal(report.summary.additional_editorial_project_candidates, 2);
assert.equal(report.summary.additional_editorial_place_candidates, 2);
assert.equal(report.summary.montana_source_projects_to_reconcile, 32);
assert.equal(report.summary.named_place_dossiers_to_reconcile, 10);
assert.equal(report.summary.jurisdiction_orientations_to_disposition, 18);
assert.equal(report.summary.unnamed_target_contracts, 48);
for (const k of ['accepted_projects','accepted_places','accepted_project_gap','accepted_place_gap']) assert.equal(report.summary[k], null);
assert.equal(report.summary.new_admissions, 0);
assert(report.entities.every(r => r.full_v1_acceptance === null));
assert(report.additional_editorial_candidates.every(r => r.canonical_id === null && r.full_v1_acceptance === null));
assert.equal(report.followup.acquisition_dockets.length, 53);
assert.equal(report.followup.acquisition_dockets.filter(r => r.current_editorial_candidate).length, 4);
assert.equal(report.mandatory_scope.translations.length, 34);
assert(report.mandatory_scope.translations.every(r => r.translated_content === null && r.approval_receipt_id === null));
assert.equal(report.mandatory_scope.portfolio_gate.state, 'Held');
assert.equal(report.mandatory_scope.annual_edition_counts.topic_chapters, 17);
assert.equal(report.mandatory_scope.annual_edition_counts.named_case_profiles, 24);
console.log('Portfolio census assertions passed: exact/type-scoped deduplication, unresolved source cohorts, four candidate overlays, 34 untranslated contracts and no invented admissions.');
