// Deliberately small fixtures test the join logic independently of the saved
// report and make missing, duplicate, changed and newly admitted rows fail.
const baseline = {projects:[{project_id:'P1',project_name:'Test - County',uei:'U1',subgrantee_id:'S1',bead_support_usd:0,subgrantee_match_usd:2,outcome_state:null}]};
const source = {records:[{project_id:'P1',name:'Test – County ',uei:'U1',bead_support:'0',subgrantee_match:'2',csv_row:2}]};
const layer = {registry:'fixture',array:'versions',idKey:'version_id',rowsPerProject:1,records:[{version_id:'V1',project_id:'P1',subgrantee_id:'S1',reporting_rail:'terrestrial',accepted_observation:null}]};
assert.equal(reconcileMontana(baseline,[layer],source).length,1);
assert.equal(reconcileMontana(baseline,[layer],source)[0].source_name,'Test – County ');
assert.throws(() => reconcileMontana(baseline,[{...layer,records:[]}],source), /Missing project/);
assert.throws(() => reconcileMontana(baseline,[{...layer,records:[...layer.records,...layer.records]}],source), /Duplicate layer row/);
assert.throws(() => reconcileMontana(baseline,[{...layer,records:[{...layer.records[0],project_id:'P2'}]}],source), /Unknown Montana/);
assert.throws(() => reconcileMontana(baseline,[{...layer,records:[{...layer.records[0],accepted_observation:1}]}],source), /new evidence requires review/);
assert.throws(() => reconcileMontana(baseline,[layer],{records:[{...source.records[0],bead_support:''}]}), /Missing or nonnumeric/);
assert.throws(() => reconcileMontana(baseline,[layer],{records:[{...source.records[0],uei:'U2'}]}), /UEI mismatch/);
assert.throws(() => reconcileMontana(baseline,[layer],{records:[...source.records,...source.records]}), /Duplicate CSV/);
assert.throws(() => reconcileMontana(baseline,[layer],{records:[{...source.records[0],subgrantee_match:'3'}]}), /amount mismatch/);
